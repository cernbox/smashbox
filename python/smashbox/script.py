config = Configuration()

def execfile(filename: str, globals: dict[str, Any], locals: Mapping[str, object] | None = None) -> None:
    """ Python 3 replacement of the execfile() builtin.
    """
    with open(filename, "rb") as f:
        code = compile(f.read(), filename, 'exec')
    exec(code, globals, locals)

# the config blob is passed as a command line argument so it must be a printable string
def configure_from_blob(config_blob: str) -> Configuration:
    import pickle, base64
    global config
    config = pickle.loads(base64.b64decode(config_blob))
    config_log(level=logging.DEBUG)
    return config

def dump_config_to_blob() -> str:
    import pickle, base64
    return base64.b64encode(pickle.dumps(config)).decode('ascii')
        
def configure(cmdline_opts: list[tuple[str, Any]] | None, config_files: list[str] | None = None) -> Configuration:
   """ Initialize config object and return it.

   First exec the sequence of config_files (including the
   main_config_file). All symbols defined by these files will be set
   as attributes of the config object.

   Then process cmdline_opts (which is a list of tuples generated by
   arg_parser). If attribute matching the option already exists (was
   defined in a configuration file) then eval to the same type (if not
   None). Otherwise leave string values. The string "None" is special
   and it is always converted to None and may always be assigned.
 
   """

   if config_files is None:
      config_files = []

   logger = getLogger()

   config_files = [main_config_file] + config_files

   for cf in config_files:
      execfile(cf,{},config.__dict__)

   if cmdline_opts:
      for key,val in cmdline_opts:
         try:
            if val == "None":
               val = None
            else:
               attr = getattr(config,key)
               # coerce val type to attr's type unless attr is set to None (then leave as-is <string>)
               try:
                  if attr is not None:
                     val = type(attr)(val)
               except ValueError as x:
                  # allow setting to None
                  logger.warning("cannot set option (type mismatch) %s=%s --> %s",key,repr(val),x)
                  continue
         except AttributeError:
            # if attr unknown then leave the val as-is (string)
            pass

         setattr(config,key,val)

   config_log(level=logging.DEBUG)
   
   return config

def config_log(level: int, hide_password: bool = False) -> None:
   """ Dump the entire configuration to the logging system at the given level.
   If hide_password=True then do not show the real value of the options which contain "password" in their names.
   """
   logger = getLogger()
   for d in dir(config):
      if not d.startswith("_") and d != "get":
          value = repr(getattr(config,d))
          if hide_password and 'password' in d:
             value = "***"
             
          logger.log(level,"CONFIG: %s = %s",d,value)


import logging

logger: logging.Logger | None = None
def getLogger(name: str = "", level: int | None = None) -> logging.Logger:
   global logger
   if not logger:
      if level is None:
          level = logging.INFO  # change here to DEBUG if you want to debug config stuff
      logging.basicConfig(level=level)

   return logging.getLogger('.'.join(['smash',name]))
